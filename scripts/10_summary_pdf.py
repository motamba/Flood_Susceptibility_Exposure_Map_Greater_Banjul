"""Step 10: one-page summary (A4 PDF) with the map and key figures.

ToR §7 D5 (one-page summary with screenshots and key figures).
Implementation Plan §11 Day 10 (planned in QGIS; built here with matplotlib
so the page is regenerated by `make all` and always matches the results).

All numbers are read from the output tables, never typed in.

Output: reports/summary.pdf (and a PNG preview, reports/summary.png)
"""
import json

import geopandas as gpd
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import rasterio
from matplotlib.colors import ListedColormap
from matplotlib.lines import Line2D
from matplotlib.patches import Patch

from flood.config import DATA_PROCESSED, ROOT, TABLES, ensure_dirs, load_config

REPORTS = ROOT / "reports"
COLOURS = ["#fed976", "#fd8d3c", "#bd0026"]   # web map palette (Plan §9)
WATER, WETLAND, FLOOD_PT = "#4a90c8", "#5fb58a", "#6a3d9a"
INK, MUTED, WARN = "#1f2328", "#5b636e", "#7a4100"


def text_block(fig, x, y, title, lines, width_note=None):
    fig.text(x, y, title, fontsize=10, fontweight="bold", color=INK, va="top")
    fig.text(x, y - 0.018, "\n".join(lines), fontsize=7.6, color=INK, va="top", linespacing=1.45)


def main() -> None:
    cfg = load_config()
    ensure_dirs()
    REPORTS.mkdir(exist_ok=True)
    p = cfg["project"]
    labels = cfg["classification"]["labels"]
    w = {k: v["weight"] for k, v in cfg["factors"].items()}

    exp = pd.read_csv(TABLES / "exposure.csv").set_index("asset")
    council = pd.read_csv(TABLES / "exposure_by_council.csv").set_index("council")
    sens = pd.read_csv(TABLES / "sensitivity.csv")
    plaus = pd.read_csv(DATA_PROCESSED / "reported_floods.csv")   # one row per place
    rain = json.loads((DATA_PROCESSED / "rainfall.json").read_text())
    with rasterio.open(DATA_PROCESSED / "susceptibility_classes.tif") as src:
        classes, t = src.read(1), src.transform
    study = gpd.read_file(DATA_PROCESSED / "study_area.gpkg", layer="study_area")
    water = gpd.read_file(DATA_PROCESSED / "water_mask.gpkg")
    pts = gpd.read_file(DATA_PROCESSED / "reported_floods.gpkg").to_crs(study.crs)

    land = exp.loc["Land area"]
    high_pct_land = land["High_pct"]
    b = exp.loc["Buildings"]
    in_high = (plaus["class"] == labels[-1]).sum()
    others = sens[sens.scenario != "S0"]
    moderate = others[others.change.str.contains(r"\+0.10|equal")]

    fig = plt.figure(figsize=(8.27, 11.69))   # A4 portrait

    # Header.
    fig.text(0.05, 0.965, p["title"], fontsize=15, fontweight="bold", color=INK, va="top")
    fig.text(0.05, 0.937, f"Banjul, Kanifing and Kombo North, The Gambia  ·  {p['author']}  ·  "
             f"personal project, November 2026", fontsize=8.5, color=MUTED, va="top")
    fig.text(0.05, 0.92, "Susceptibility index for learning, not a flood forecast. "
             "Do not use for planning or safety decisions.", fontsize=8.5, color=WARN,
             fontweight="bold", va="top")

    # Map.
    ax = fig.add_axes([0.03, 0.47, 0.60, 0.44])
    ext = (t.c, t.c + classes.shape[1] * t.a, t.f + classes.shape[0] * t.e, t.f)
    ax.imshow(np.where(classes > 0, classes, np.nan), extent=ext, cmap=ListedColormap(COLOURS),
              vmin=0.5, vmax=3.5, interpolation="nearest")
    water[water["type"] == "water"].plot(ax=ax, color=WATER, linewidth=0)
    water[water["type"] == "wetland"].plot(ax=ax, facecolor="none", edgecolor=WETLAND,
                                          linewidth=0.3, hatch="////", alpha=0.6)
    study.boundary.plot(ax=ax, color=INK, linewidth=0.7)
    pts.plot(ax=ax, color=FLOOD_PT, markersize=22, edgecolor="white", linewidth=0.8, zorder=5)
    ax.set_axis_off()
    handles = [Patch(color=c, label=f"{l} susceptibility") for l, c in zip(labels, COLOURS)]
    handles += [Patch(color=WATER, label="Open water (excluded)"),
                Patch(facecolor="none", edgecolor=WETLAND, hatch="////", label="Wetland / mangrove"),
                Line2D([], [], marker="o", color="w", markerfacecolor=FLOOD_PT, markersize=7,
                       label="Place reported flooded (news)")]
    ax.legend(handles=handles, loc="lower left", fontsize=6.8, frameon=True, framealpha=0.9)
    x0, y0 = ext[0] + 1500, ext[2] + 300
    ax.plot([x0, x0 + 5000], [y0, y0], color=INK, linewidth=2)
    ax.text(x0 + 2500, y0 + 350, "5 km", ha="center", fontsize=7)

    # Key figures.
    kx, ky = 0.66, 0.895
    fig.text(kx, ky, "Key figures", fontsize=10, fontweight="bold", color=INK, va="top")
    facts = [
        (f"{land['High']:.0f} km²", f"High susceptibility: {high_pct_land:.0f}% of the land"),
        (f"{b['High']:,.0f}", f"buildings in High ({b['High_pct']:.0f}% of {b['Total']:,.0f})"),
        (f"{council.loc['banjul', 'buildings_high_pct']:.0f}%", "of Banjul's buildings are in High"),
        (f"{exp.loc['Schools', 'High']:.0f} + {exp.loc['Health facilities', 'High']:.0f}",
         "schools + health facilities in High"),
        (f"{in_high} of {len(plaus)}", f"places reported flooded lie in High\n(High = {high_pct_land:.0f}% of land)"),
        (f"{rain['climatology']['wet_season_share']:.0%}",
         f"of the {rain['climatology']['normal_annual_mm']:,} mm annual rain\nfalls June–October"),
    ]
    y = ky - 0.03
    for big, small in facts:
        fig.text(kx, y, big, fontsize=15, fontweight="bold", color=COLOURS[2], va="top")
        fig.text(kx, y - 0.024, small, fontsize=7.6, color=INK, va="top", linespacing=1.3)
        y -= 0.064
    fig.text(kx, y + 0.01, "Counts are minimum values (OpenStreetMap\nis incomplete; data of "
             f"{str(exp['osm_data_as_of'].iloc[0])[:10]}).", fontsize=6.8, color=MUTED, va="top")

    # Exposure chart: share in High vs share of land.
    ax = fig.add_axes([0.17, 0.285, 0.31, 0.15])
    order = ["Land area", "Buildings", "Roads (vehicle)", "Schools", "Health facilities"]
    vals = [exp.loc[a, "High_pct"] for a in order]
    ax.barh(order, vals, color=[MUTED] + [COLOURS[2]] * 4, height=0.6)
    for i, v in enumerate(vals):
        ax.text(v + 1, i, f"{v:.0f}%", va="center", fontsize=7)
    ax.invert_yaxis()
    ax.set_xlim(0, 50)
    ax.tick_params(labelsize=7)
    ax.set_title("Share in the High class (grey = land, for reference)", fontsize=8, loc="left")
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)

    # Rainfall chart.
    ax = fig.add_axes([0.60, 0.285, 0.35, 0.15])
    c = rain["climatology"]
    x = np.arange(12)
    ax.bar(x, c["normal_mm"], color=WATER, width=0.65, label=f"Normal {c['period']}")
    ax.plot(x, c["example_mm"], "o", color=INK, markersize=3.5, label=str(c["example_year"]))
    ax.set_xticks(x, [m[0] for m in c["months"]], fontsize=7)
    ax.tick_params(labelsize=7)
    ax.set_ylabel("mm/month", fontsize=7)
    ax.legend(fontsize=6.5, frameon=False, loc="upper left")
    ax.set_title("Monthly rainfall (CHIRPS v3)", fontsize=8, loc="left")
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)

    # Method and limitations.
    text_block(fig, 0.05, 0.245, "Method", [
        "1. Bare-earth DEM (FABDEM, 30 m); hollows breached, not filled, so",
        "    flow can be routed without erasing ponding areas.",
        f"2. Five factors scaled 0–1: HAND {w['hand']:.2f}, elevation {w['elevation']:.2f},",
        f"    depression depth {w['depression_depth']:.2f}, wetness index {w['twi']:.2f}, land cover {w['landcover']:.2f}.",
        "3. Weighted sum classed Low / Medium / High (Jenks natural breaks).",
        f"4. 11 alternative weightings: High zone keeps {moderate.jaccard_vs_S0.min():.2f}–"
        f"{moderate.jaccard_vs_S0.max():.2f} overlap",
        "    under moderate changes (Jaccard); elevation matters most.",
        "5. OSM assets counted per class; check against news-reported floods.",
    ])
    text_block(fig, 0.53, 0.245, "Limitations", [
        "• 30 m terrain cannot see drains or culverts; blocked drains,",
        "   a main local cause of flooding, are not in the model.",
        f"• No observed flood map; the news check uses only {len(plaus)} places.",
        "• Weights are expert judgement; buildings in High range",
        f"   {others.buildings_high_pct.min():.0f}–{others.buildings_high_pct.max():.0f}% across scenarios.",
        "• OSM is incomplete; rainfall cells are about 5.5 km wide.",
    ])

    # Footer.
    fig.add_artist(Line2D([0.05, 0.95], [0.085, 0.085], color="#d8dde3", linewidth=0.8))
    fig.text(0.05, 0.075, f"Live map: {p['live_url']}\nCode and full method: {p['repo_url']}",
             fontsize=7.6, color=INK, va="top", linespacing=1.5)
    fig.text(0.05, 0.045,
             "Data: FABDEM V1-2 (Univ. of Bristol, CC BY-NC-SA 4.0) from Copernicus DEM GLO-30 © DLR, Airbus; "
             "ESA WorldCover 2021 (CC BY 4.0);\n© OpenStreetMap contributors (ODbL); CHIRPS v3 (UCSB CHC; "
             "Funk et al. 2026); geoBoundaries (CC BY 4.0); Gambian news reports (cited in the repository).",
             fontsize=6.3, color=MUTED, va="top", linespacing=1.45)

    fig.savefig(REPORTS / "summary.pdf")
    fig.savefig(REPORTS / "summary.png", dpi=110)
    print(f"[ok] {REPORTS / 'summary.pdf'}")


if __name__ == "__main__":
    main()
